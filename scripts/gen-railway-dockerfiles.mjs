/**
 * Railway's Dockerfile builder cannot select a multi-stage target, so each
 * service gets its own Dockerfile whose LAST stage is the one to run. They
 * are generated from the root Dockerfile so the two never drift.
 *
 *   node scripts/gen-railway-dockerfiles.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync(new URL("../Dockerfile", import.meta.url), "utf8");
const marker = "# ---------------------------------------------------------------------------";
const blocks = src.split(marker);
const header = blocks[0];
const stages = blocks.slice(1);
const byName = new Map();
for (const s of stages) {
  const m = s.match(/FROM [^\n]+ AS ([a-z-]+)/);
  if (m) byName.set(m[1], s);
}
const shared = ["base"].map((n) => byName.get(n)).join(marker);
const services = ["api", "worker", "web"];
mkdirSync(new URL("../railway", import.meta.url), { recursive: true });
for (const svc of services) {
  let stage = byName.get(svc);
  if (svc === "api") {
    // Railway has no compose `migrate` one-shot: the API image applies
    // migrations and seeds (both idempotent) before it starts listening.
    stage = stage.replace(
      'CMD ["node", "dist/server.js"]',
      'CMD ["sh", "-c", "node dist/cli.js migrate seed && node dist/server.js"]',
    );
  }
  const out = [
    "# GENERATED by scripts/gen-railway-dockerfiles.mjs from the root Dockerfile. Do not edit.\n" + header.replace(/^# syntax[^\n]*\n/, "# syntax=docker/dockerfile:1.7\n"),
    shared,
    stage,
  ].join(marker);
  writeFileSync(new URL(`../railway/Dockerfile.${svc}`, import.meta.url), out);
  console.log(`railway/Dockerfile.${svc}`);
}
